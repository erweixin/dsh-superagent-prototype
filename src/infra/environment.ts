/** Worker PATH shims: default command routing, not an OS sandbox. */
import { mkdir, readdir, readFile, lstat, writeFile, rename, unlink } from 'node:fs/promises'
import { join } from 'node:path'
import type { Deployment } from '../deployment.ts'
const marker = '# Generated by feishu-superagent'
export const workerBin = (stateDir: string) => join(stateDir, 'worker-bin')
const quote = (s: string) => "'" + s.replaceAll("'", "'\\''") + "'"
export async function writeEnvironment(deployment: Deployment, blocked: readonly string[], sourceShims: Readonly<Record<string, string>> = {}) {
  const directory = workerBin(deployment.stateDir)
  await mkdir(directory, { recursive: true })
  const before = await readdir(directory)
  for (const name of before) {
    const file = join(directory, name)
    if (!(await lstat(file)).isFile() || !(await readFile(file, 'utf8')).includes(marker))
      throw new Error(`Unmanaged file in worker-bin: ${name}`)
  }
  const valid = (name: string) => /^[a-zA-Z0-9._-]+$/.test(name) && name !== '.' && name !== '..'
  for (const name of Object.keys(sourceShims)) if (!valid(name)) throw new Error('Invalid source command')
  const shims: Record<string, string> = { ...sourceShims }
  for (const name of blocked) {
    if (!valid(name) || name in sourceShims)
      throw new Error('Invalid blocked command')
    shims[name] = `echo ${quote(`${name} is blocked by the operator`)} >&2\nexit 1`
  }
  for (const [name, body] of Object.entries(shims)) {
    const tmp = join(directory, `.${name}.tmp`)
    await writeFile(tmp, `#!/bin/sh\n${marker}\n${body}\n`, { mode: 0o700 })
    await rename(tmp, join(directory, name))
  }
  for (const name of before) if (!(name in shims)) await unlink(join(directory, name))
}
